// Generates a compact "land dot" list for the dotted globe (run once, output embedded in land.js)
import { readFileSync, writeFileSync } from 'node:fs'

const geo = JSON.parse(readFileSync(new URL('./ne_110m_land.geojson', import.meta.url), 'utf8'))

const polys = []
for (const f of geo.features) {
  const g = f.geometry
  const sets = g.type === 'Polygon' ? [g.coordinates] : g.coordinates
  for (const rings of sets) polys.push(rings[0]) // outer ring only, enough for a mask
}

function inRing(lon, lat, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}

function onLand(lon, lat) {
  for (const ring of polys) if (inRing(lon, lat, ring)) return true
  return false
}

const STEP = 2.5
const dots = []
for (let lat = -57.5; lat <= 80; lat += STEP) {
  for (let lon = -180; lon < 180; lon += STEP) {
    if (onLand(lon, lat)) dots.push(`${lat.toFixed(1)} ${lon.toFixed(1)}`)
  }
}

writeFileSync(
  new URL('./land.js', import.meta.url),
  '// Auto-generated by gen-land.mjs — "lat lon" pairs marking land for the dotted globe\nwindow.LAND_DOTS = "' +
    dots.join(';') +
    '"\n'
)
console.log('dots:', dots.length)
